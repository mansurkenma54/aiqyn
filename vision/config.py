"""AIQYN Vision — барлық баптаулар бір жерде.

Баптау реті (кейінгісі алдыңғысын басып жазады):
    1) осы файлдағы әдепкі мәндер
    2) config.json
    3) командалық жол аргументтері (--conf, --source, ...)
"""

from __future__ import annotations

import json
from dataclasses import dataclass, asdict, fields
from pathlib import Path
from typing import Optional

# aiqyn/vision/config.py -> aiqyn/
ROOT = Path(__file__).resolve().parent.parent


@dataclass
class Config:
    # ---------- Видео көзі ----------
    source: str = "phone"                 # phone | file | rtsp
    phone_host: str = "192.168.42.129"    # USB tethering кезіндегі әдепкі мекенжай
    phone_port: int = 8080
    video_path: str = ""                  # source=file болғанда
    rtsp_url: str = ""                    # source=rtsp (Sergek/CCTV/дрон — Phase 2)
    file_realtime: bool = True            # файлды нақты уақыт жылдамдығымен ойнату

    # ---------- Детекция ----------
    weights: str = "models/RDD_best.pt"   # YOLOv8, RDD2022-де үйретілген
    # Өлшеу нәтижесі (үш далалық видео, IMG_7710/7712/7713):
    #   0.60 — шын шұңқырлардың жартысы шегінен өтпеді
    #   0.45 — шұңқыр табылады, БІРАҚ қиратылған асфальт (0.25-0.58) және
    #          көлеңкедегі ақау (0.40) жоғалып кетеді
    #   0.30 — үш ақау да табылады, таза жолда (IMG_7713) жалған сигнал ЖОҚ
    #   0.20 — таза жолда 3 жалған сигнал шығады
    # Сондықтан 0.30 таңдалды.
    conf_threshold: float = 0.30
    imgsz: int = 640
    # "auto"      — ең жылдам қолжетімді құрылғыны өзі табады (ұсынылады)
    # "cpu"       — әрқашан процессор
    # "intel:gpu" — Intel кірістірілген графикасы (OpenVINO)
    # "0"         — NVIDIA CUDA
    #
    # Осы ноутбукте өлшенді (Intel i5-1135G7 + Iris Xe):
    #   PyTorch CPU  104 мс  (9.6 талдау/сек)
    #   Iris Xe GPU   29 мс  (34.6 талдау/сек)  <- 3.6 есе жылдам,
    #                                             детекция саны бірдей
    device: str = "auto"
    min_box_area_frac: float = 0.0015     # тым ұсақ bbox-тарды алып тастау

    # ---------- Талдау ағыны ----------
    # МАҢЫЗДЫ. CPU-да бір кадрды талдау ~350 мс алады. Бұрын ол негізгі
    # циклде жүретін де, видео секундына 7 кадрмен — «баяу түсірілім»
    # сияқты — ойналатын. Енді талдау БӨЛЕК АҒЫНДА жүреді: көрініс толық
    # жылдамдықпен (25-30 кадр/сек) жүреді, ал талдаушы өз қарқынымен
    # ЕҢ СОҢҒЫ кадрды алады. Ешқандай кезек жиналмайды.
    async_detect: bool = True
    detect_max_hz: float = 0.0            # 0 = шектеусіз (мүмкіндігінше жиі)
    frame_stride: int = 5                 # тек async_detect=false болғанда

    # ВИДЕОФАЙЛ үшін кадр тастамау. Тірі камерада талдаушы бос болмаса кадр
    # тасталады — көрініс артта қалмауы керек. Файлда «артта қалу» деген жоқ,
    # сондықтан әр кадр талданады: нәтиже толық әрі әр жүргізуде БІРДЕЙ.
    # Өлшенді (test.MOV, 126 кадр): 41 кадр/3 ақау -> 126 кадр/6 ақау.
    file_full_scan: bool = True

    # ---------- Дәлдеу режимі (tiling) ----------
    # Толық кадрдан бөлек, жол көрінетін бөлікті ЕКІ кесіндіге бөліп те
    # талдау. Үш далалық видеода өлшенді: 3 детекция -> 11 детекция.
    # Қосымша табылғандары көзбен тексерілді — шын жарықтар.
    # Бағасы: бір талдау ~3 есе ұзақ (94 мс -> 303 мс), бірақ талдау
    # бөлек ағында жүргендіктен видео бұрынғыдай тегіс жүреді.
    tile_detect: bool = True
    tile_top_frac: float = 0.40           # кесінділер кадрдың осы деңгейінен басталады

    # Бір ақаудың бөлшектерін біріктіру. Асфальттың үлкен қирау аймағын
    # модель 2-3 бөлек қорап етіп береді — есепте ол БІР ақау болуы керек.
    merge_fragments: bool = True
    merge_gap_px: int = 90                # осыдан жақын қораптар бір ақау саналады

    # Кадрды қию: телефон көлікте тұрғанда кадрдың төменгі бөлігін кейде
    # көліктің панелі (торпедо) алып қалады.
    #
    # ЕСКЕРТУ: әдепкіде 0 — ЕШТЕҢЕ КЕСІЛМЕЙДІ. Себебі өлшенді: шұңқыр
    # кадрдың дәл ТӨМЕНГІ 25%-ында көрінеді (көлікке ең жақын жер), ал
    # «төменін 30% кесу» дәл сол аймақты жойып, детекцияны нөлге
    # түсіретін. Панель шынымен көрініп тұрса ғана қолданыңыз.
    crop_top_frac: float = 0.0
    crop_bottom_frac: float = 0.0

    enable_yolo: bool = True
    # Шұңқырды физикалық белгісі бойынша табатын екінші детектор.
    #
    # ӘДЕПКІДЕ ӨШІРУЛІ. Себебі өлшенді: симуляцияда ол recall-ды
    # 10%-дан 58%-ға көтереді, БІРАҚ нақты далалық бейнеде жаяу
    # жүргіншіні, ескі жамауды және көлеңкені шұңқыр деп танып,
    # шын детекцияны басып тастайды. Нақты жолда YOLO әлдеқайда
    # сенімді. Симулятормен тексергенде қосуға болады:
    #     --pothole-cv   немесе  config.json: "enable_pothole_cv": true
    enable_pothole_cv: bool = False
    enable_flood: bool = False            # су тасу (rule-based)
    # Көше жарығы детекторы ӘДЕЙІ ӨШІРУЛІ. Ол жалған сигнал көп берді
    # (өлшенген precision 21%), әрі жоба қазір БІР МІНДЕТКЕ — жол
    # ақауын дәл табуға — шоғырланған. Қажет болса қайта қосыңыз.
    enable_streetlight: bool = False      # көше жарығы (түнгі режим, rule-based)

    # ---------- Жол ақауын нақтылау ----------
    # Ақауды тек жол бетінен іздеу (шөптегі дақ, тротуар, ғимарат сүзіледі).
    #
    # ӘДЕПКІДЕ ӨШІРУЛІ. Себебі өлшенді: далалық видеода жол шекарасын
    # табатын алгоритм ШЫН шұңқырларды да тастап жіберді (кадрдың төменгі
    # жиегіндегі ақау маскаға кірмей қалады), әрі әр кадрға 79 мс қосты.
    # RDD моделі жол көрінісіне үйретілген, сондықтан ол сүзгісіз де
    # шөптен шұңқыр таппайды. Қажет болса қайта қосуға болады.
    road_only: bool = False

    # КАДРДЫҢ ЖИЕГІН ЕСКЕРМЕУ (жүру дәлізі).
    #
    # Камера қапталында әрқашан жол ЕМЕС бет тұрады: бордюр, науа, тротуар,
    # қиыршық тас, шөп. Модель ондағы дақты «ақау» деп табуы мүмкін, ал ол
    # жерге жөндеу тапсырысы ашылмайды.
    #
    # Мән — кадр енінің үлесі, әр жақтан бөлек. 0 = сүзгі өшірулі.
    # Камераны бекіткеннен кейін бірнеше кадрды қарап реттеңіз: ақаудың
    # ОРТАСЫ осы дәліздің ішінде болуы керек.
    # Өлшенді (test.MOV): оң жақтан 0.10 — тротуардағы жалған сигнал кетті,
    # жолдың шетіндегі шын шұңқыр (ортасы 0.86) қалды.
    roi_left_frac: float = 0.0
    roi_right_frac: float = 0.0
    road_margin_px: int = 12              # шекарадан сәл кеңірек рұқсат

    # Уақыт бойынша растау: нағыз шұңқыр көлік жақындаған сайын
    # БІРНЕШЕ кадрда қатарынан көрінеді. Бір кадрда жарқ ете қалған
    # нәрсе — шу. Бұл жалған детекцияны күрт азайтады.
    # ӘДЕПКІДЕ ӨШІРУЛІ (1 = растау жоқ). Себебі өлшенді: далалық
    # бейнеде YOLO бір шұңқырды бар болғаны 1-2 кадрда табады, ал
    # растау 2 рет көрінуді талап еткенде ШЫН шұңқыр да жоғалып кетті.
    # Детекция ТЫҒЫЗ болатын жағдайда (жақсы жарық, баяу жүріс) 2-ге
    # қойған пайдалы: симуляцияда ол шуды 1429-дан 115-ке түсірді.
    confirm_frames: int = 1               # осынша кадрда көрінуі керек

    # Нысан осынша талданған кадр ішінде қайта көрінсе — СОЛ нысан.
    #
    # Терезе тым қысқа болса, бір ақау ЕКІ рет тіркеледі: көлік жақындағанда
    # модель оны бір сәтке жоғалтып алады да (бұрылыс, көлеңке, шаң), қайта
    # көргенде жаңа нысан деп санайды. Өлшенді (test.MOV): терезе 6 болғанда
    # бір шұңқыр 75 және 109-кадрда екі бөлек оқиға болып шықты; терезе 20
    # болғанда дұрыс — бір оқиға.
    confirm_window: int = 20
    track_iou: float = 0.20               # кадрлар арасында бір нысан деп санау шегі

    # Нысанның ортасы өз енінен осынша есе жылжыса — сол нысан.
    # Тым үлкен болса, жол бойындағы БӨЛЕК ақаулар бір тізбекке қосылып
    # кетеді. Өлшенді (test.MOV): 2.2 -> бәрі бір оқиға, 0.8 -> дұрыс бөлінеді.
    track_center_gap: float = 0.8

    # Бір нысанды КЛАСС бойынша бөлмеу. Модель бір қирау аймағын бір кадрда
    # «торлы жарық», келесісінде «шұңқыр» деуі мүмкін — сонда БІР ақау ЕКІ
    # құжат болып тіркеледі. Нысан ОРНЫ бойынша бақыланады, класты трек
    # бойындағы ең сенімді детекция шешеді.
    track_cross_class: bool = True
    night_brightness: float = 65.0        # кадрдың орташа жарықтығы < осы => түн

    # ---------- Дәлел (evidence) ----------
    evidence_dir: str = "evidence"
    pre_roll_sec: float = 3.0             # оқиғаға дейінгі
    post_roll_sec: float = 5.0            # оқиғадан кейінгі  => клип ~8 сек
    clip_fps: float = 15.0
    # Дәлел КЛИПІНІҢ ені (пиксель). Ресми ФОТО бұған тәуелсіз, әрқашан
    # толық ажыратымдылықта сақталады. 1080p клип жадта 1,5 ГБ орын алып,
    # бағдарламаны тежейтін — 960 px дәлел ретінде әбден жеткілікті.
    clip_width: int = 960
    use_shot_jpg: bool = True             # ең анық кадрды /shot.jpg-тен жоғары сапада алу

    # ---------- GPS ----------
    gps_poll_hz: float = 2.0
    stream_latency_sec: float = 0.80      # МАҢЫЗДЫ: MJPEG ағынының кідірісі.
                                          # Кадрдың нақты уақыты = алынған уақыт - осы.
    gps_max_extrapolate_sec: float = 3.0  # одан әрі ескі фикс "сенімсіз" деп белгіленеді
    fallback_lat: float = 42.31560        # GPS жоқ кезде (демо/файл режимі) — Шымкент
    fallback_lon: float = 69.58690
    manual_lat: Optional[float] = None    # --lat: телефон GPS-і істемесе қолмен беру
    manual_lon: Optional[float] = None    # --lon
    gps_track: str = ""                   # --gps-track: жазылған трек (jsonl)

    # ---------- Жөндеу аймақтары ----------
    # Оператор сайттан белгілеген жөндеу/жабық аймақтардағы ақаулар бойынша
    # құжат құрылмайды — ол жерде жұмыс бұрыннан жүріп жатыр.
    skip_in_zones: bool = True
    zones_refresh_sec: float = 60.0

    # ---------- Дедупликация ----------
    # ЖӨНДЕУ УЧАСКЕСІ. Осы қашықтықтағы ақаулар БІР жұмыс тапсырысы болады.
    #
    # Неге керек: жол жиегіндегі ұзын бұзылған жолақты модель бірнеше бөлек
    # ақау деп табады, ал жөндеу бригадасы оны БІР рет келіп бітіреді.
    # Мұндай топтастыру муниципалдық тізілім тәжірибесіне сай.
    # 25 м тым үлкен болатын (бүкіл көше бір нүктеге жиналатын), 10 м —
    # test.MOV бойынша өлшеніп таңдалды.
    dedup_radius_m: float = 10.0

    # Топтастыру класс бойынша бөлінбейді: бір учаскедегі «торлы жарық» пен
    # «шұңқыр» — бригада үшін бір жұмыс.
    dedup_cross_class: bool = True
    # 0 = сессия бойы есте сақтау: бір ақау бір сапарда БІР РЕТ қана
    # тіркеледі, тіпті сол жерден қайта өтсеңіз де қайталанбайды
    dedup_window_sec: float = 0.0

    # GPS ЖОҚ болғанда (видеофайл, fallback нүкте) орын бойынша сүзудің
    # мәні жоқ — бүкіл сапар бір нүктеде. Ондайда бір ақау = бір оқиға
    # деген шешімді уақыт бойынша растау қабаты шығарады, ал мұнда тек
    # осы қысқа терезе ішіндегі қайталауды ұстаймыз.
    dedup_untrusted_gap_sec: float = 1.0

    # Орын бойынша сүзу тек осы уақыттан ЕСКІ жазбаларға қолданылады.
    #
    # Неге керек: бір көшеде 25 метр ішінде бірнеше БӨЛЕК шұңқыр болуы —
    # қалыпты жағдай, әрқайсысы жеке жөндеу нысаны. Олардың бөлек екенін
    # уақыт бойынша растау қабаты кадрдан кадрға бақылап анықтайды, ал ол
    # GPS-тен (қатесі 5-15 м) дәлірек. Сондықтан жаңа ғана табылған ақау
    # орын бойынша сүзілмейді.
    #
    # Ал сол көшеден 20 секундтан кейін ҚАЙТА өтсеңіз — бұл сүзгі
    # қайталанған құжатты болдырмайды.
    dedup_min_gap_sec: float = 0.0

    # ---------- Мекенжай ----------
    geocode_enabled: bool = True
    geocode_provider: str = "auto"        # auto | nominatim | 2gis
    nominatim_url: str = "https://nominatim.openstreetmap.org/reverse"
    nominatim_email: str = ""             # Nominatim саясаты бойынша ұсынылады
    geocode_timeout: float = 6.0
    gis2_key: str = ""                    # .env: AIQYN_2GIS_KEY

    # ---------- Координатаны жолға түсіру ----------
    # GPS 5-15 метрге қателеседі, сондықтан белгі картада жолдың
    # үстінде емес, шөпте тұрып қалады. Бұл соны түзетеді.
    snap_to_road: bool = True
    snap_search_radius_m: float = 120.0   # осы радиустағы көшелер қаралады
    snap_max_distance_m: float = 25.0     # одан алыс болса — түзетілмейді

    # ---------- ИИ-тексеруші (екінші саты) ----------
    # Кілт .env файлынан алынады. Кілт болмаса — өшірулі күйде қалады,
    # жүйе бұрынғыдай жұмыс істейді.
    ai_verify: bool = True
    ai_provider: str = "gemini"           # gemini | openai
    ai_api_key: str = ""                  # .env: AIQYN_AI_API_KEY
    # Қосымша кілттер (.env: AIQYN_AI_API_KEY_2, _3 ...). Әр кілттің
    # тегін лимиті БӨЛЕК, сондықтан біреуі бітсе — келесісіне ауысамыз.
    ai_api_keys: tuple = ()
    ai_model: str = "gemini-3.1-flash-lite"   # .env: AIQYN_AI_MODEL
    # Тегін лимит біткенде автоматты ауысатын қосалқы модельдер.
    # Далалық тест ортасында ИИ үнсіз өшіп қалмауы үшін.
    ai_model_fallbacks: tuple = (
        "gemini-3.1-flash-lite",
        "gemini-2.5-flash-lite",
        "gemini-flash-lite-latest",
        "gemini-2.5-flash",
        "gemini-flash-latest",
    )
    ai_base_url: str = ""                 # openai үйлесімді қызмет үшін
    ai_timeout: float = 25.0
